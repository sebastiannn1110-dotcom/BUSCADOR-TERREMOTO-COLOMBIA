-- Public death confirmation requires meaningful authority and reason values,
-- not merely non-NULL placeholders. NOT VALID protects future writes without
-- blocking deployment until any historical records can be reviewed.
alter table public.cases
  add constraint cases_deceased_confirmation_details_check
  check (
    condition_status <> 'deceased_confirmed'
    or (
      verification_level = 'authority_confirmed'
      and nullif(btrim(authority_reference_private), '') is not null
      and nullif(btrim(resolution_notes_private), '') is not null
    )
  ) not valid;

-- Resolve a fictional card reference only through this read RPC. The route
-- below permits that reference solely when its own demo environment is on;
-- submit_public_report itself accepts UUIDs only.
create or replace function public.get_public_case(case_slug text)
returns setof public.public_case_cards
language sql
stable
security definer
set search_path = pg_catalog, public, pg_temp
as $$
  select v.*
  from public.public_case_cards v
  join public.cases c on c.id = v.id
  join public.people p on p.id = c.person_id
  where v.slug = case_slug
     or (p.is_test_data and p.test_key = case_slug)
$$;

-- Status updates already require staff RLS. Executing this trigger as its
-- owner lets the required history and audit inserts succeed without granting
-- staff arbitrary access to audit_logs.
create or replace function public.case_safety_trigger()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
begin
  if new.condition_status = 'deceased_confirmed' and (
    new.verification_level <> 'authority_confirmed'
    or nullif(btrim(new.authority_reference_private), '') is null
    or nullif(btrim(new.resolution_notes_private), '') is null
    or (
      not public.is_admin()
      and not (
        coalesce(current_setting('app.enable_test_data', true), 'false') = 'true'
        and exists (select 1 from public.people where id = new.person_id and is_test_data)
      )
    )
  ) then
    raise exception 'Only an admin can confirm a death with authority reference and reason';
  end if;

  if tg_op = 'INSERT' and new.condition_status = 'deceased_confirmed' then
    if auth.uid() is null then
      raise exception 'An actor is required';
    end if;

    insert into public.status_history (
      case_id,
      previous_condition,
      new_condition,
      previous_verification,
      new_verification,
      reason,
      authority_reference_private,
      actor_id
    ) values (
      new.id,
      null,
      new.condition_status,
      null,
      new.verification_level,
      new.resolution_notes_private,
      new.authority_reference_private,
      auth.uid()
    );

    insert into public.audit_logs (actor_id, action, entity_type, entity_id)
    values (auth.uid(), 'case_deceased_confirmed_created', 'case', new.id);
  elsif tg_op = 'UPDATE' and new.condition_status is distinct from old.condition_status then
    if auth.uid() is null then
      raise exception 'An actor is required';
    end if;

    insert into public.status_history (
      case_id,
      previous_condition,
      new_condition,
      previous_verification,
      new_verification,
      reason,
      authority_reference_private,
      actor_id
    ) values (
      new.id,
      old.condition_status,
      new.condition_status,
      old.verification_level,
      new.verification_level,
      coalesce(new.resolution_notes_private, 'Status update'),
      new.authority_reference_private,
      auth.uid()
    );

    insert into public.audit_logs (actor_id, action, entity_type, entity_id)
    values (auth.uid(), 'case_status_changed', 'case', new.id);
  end if;

  new.updated_at := now();
  return new;
end;
$$;

revoke all on function public.case_safety_trigger() from public;
