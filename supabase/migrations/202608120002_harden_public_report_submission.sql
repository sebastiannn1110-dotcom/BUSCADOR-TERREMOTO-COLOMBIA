-- Persist only a keyed hash generated by the server, never an IP address.
-- This is intentionally database-backed so the limit survives server restarts
-- and applies across multiple Render instances.
create table if not exists public.submission_rate_limits (
  request_fingerprint text primary key check (request_fingerprint ~ '^[0-9a-f]{64}$'),
  window_started_at timestamptz not null default now(),
  submission_count integer not null default 0 check (submission_count >= 0),
  updated_at timestamptz not null default now()
);
alter table public.submission_rate_limits enable row level security;
revoke all on table public.submission_rate_limits from public, anon, authenticated, service_role;

